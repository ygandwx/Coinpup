CREATE TABLE platform_transfers (
    id UUID NOT NULL,
    owner_id UUID NOT NULL,
    kind VARCHAR(10) NOT NULL,
    source_ledger_id UUID NOT NULL,
    source_account_id UUID NOT NULL,
    source_asset_id VARCHAR(200) NOT NULL,
    source_operation_id UUID NOT NULL,
    destination_ledger_id UUID NOT NULL,
    destination_account_id UUID NOT NULL,
    destination_asset_id VARCHAR(200) NOT NULL,
    destination_operation_id UUID,
    amount NUMERIC(38, 18) NOT NULL,
    transaction_date DATE NOT NULL,
    description VARCHAR(2000) NOT NULL,
    version INTEGER NOT NULL,
    create_key VARCHAR(128) NOT NULL,
    cancel_key VARCHAR(128),
    PRIMARY KEY (id),
    CONSTRAINT fk_platform_transfers_source_owner FOREIGN KEY(source_ledger_id, owner_id) REFERENCES ledgers (id, owner_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_destination_owner FOREIGN KEY(destination_ledger_id, owner_id) REFERENCES ledgers (id, owner_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_source_link FOREIGN KEY(source_account_id, source_asset_id, source_ledger_id) REFERENCES account_assets (account_id, asset_id, ledger_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_destination_link FOREIGN KEY(destination_account_id, destination_asset_id, destination_ledger_id) REFERENCES account_assets (account_id, asset_id, ledger_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_source_operation FOREIGN KEY(source_operation_id, source_ledger_id) REFERENCES financial_operations (id, ledger_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_destination_operation FOREIGN KEY(destination_operation_id, destination_ledger_id) REFERENCES financial_operations (id, ledger_id) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_create_receipt FOREIGN KEY(source_ledger_id, create_key) REFERENCES command_receipts (ledger_id, key) ON DELETE RESTRICT,
    CONSTRAINT fk_platform_transfers_cancel_receipt FOREIGN KEY(source_ledger_id, cancel_key) REFERENCES command_receipts (ledger_id, key) ON DELETE RESTRICT,
    CONSTRAINT uq_platform_transfers_source_operation UNIQUE (source_operation_id),
    CONSTRAINT uq_platform_transfers_destination_operation UNIQUE (destination_operation_id),
    CONSTRAINT ck_platform_transfers_kind CHECK (kind IN ('deposit', 'withdrawal')),
    CONSTRAINT ck_platform_transfers_pair CHECK (source_account_id <> destination_account_id AND source_asset_id <> destination_asset_id AND ((source_ledger_id = destination_ledger_id AND destination_operation_id IS NULL) OR (source_ledger_id <> destination_ledger_id AND destination_operation_id IS NOT NULL AND source_operation_id <> destination_operation_id))),
    CONSTRAINT ck_platform_transfers_version CHECK ((version = 1 AND cancel_key IS NULL) OR (version = 2 AND cancel_key IS NOT NULL AND create_key <> cancel_key)),
    CONSTRAINT ck_platform_transfers_amount CHECK (amount > 0 AND amount < 100000000000000000000)
);
CREATE INDEX ix_platform_transfers_destination ON platform_transfers (destination_ledger_id, transaction_date, id);
CREATE INDEX ix_platform_transfers_source ON platform_transfers (source_ledger_id, transaction_date, id);
