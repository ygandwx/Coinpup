const byId = new Map(INSTITUTIONS.map((item) => [item.id, item]));

export const BANK_INSTITUTIONS = INSTITUTIONS.filter(
    (item) => item.categories.includes("bank") || item.categories.includes("digital-bank"),
);

export const CRYPTO_PLATFORMS = INSTITUTIONS.filter((item) =>
    item.categories.includes("crypto-platform"),
);

const paymentInstitutions = new Map([
    ["wechat", "wechat"],
    ["alipay", "alipay"],
    ["paypal", "paypal"],
    ["wise", "wise-eu"],
    ["stripe", "stripe"],
]);

export function getInstitution(id?: string | null): Institution | undefined {
    return id ? byId.get(id) : undefined;
}

function normalizedName(value: string): string {
    return value
        .normalize("NFKC")
        .toLowerCase()
        .replace(/[^\p{L}\p{N}]+/gu, " ")
        .trim();
}

const namesById = new Map(
    INSTITUTIONS.map(({ id, name, shortName, aliases }) => [
        id,
        new Set([name.zh, name.en, shortName, ...aliases].map(normalizedName)),
    ]),
);

function matchingNames(value: string, candidates: readonly Institution[]): Institution[] {
    const normalized = normalizedName(value);
    if (!normalized) return [];
    const exact = candidates.filter((item) => namesById.get(item.id)?.has(normalized));
    if (exact.length) return exact;
    return candidates.filter((item) =>
        [...(namesById.get(item.id) ?? [])].some((name) =>
            /\p{Script=Han}/u.test(name)
                ? name.length >= 2 && normalized.includes(name)
                : name.length >= 3 && ` ${normalized} `.includes(` ${name} `),
        ),
    );
}

function matchingSwift(swift: string, candidates: readonly Institution[]): Institution[] {
    const value = swift.trim().toUpperCase();
    if (!/^(?:[A-Z]{4}|[A-Z]{6}[A-Z0-9]{2}(?:[A-Z0-9]{3})?)$/.test(value)) return [];
    const exact = candidates.filter((item) => item.swiftPrefix === value.slice(0, 8));
    return exact.length
        ? exact
        : candidates.filter((item) =>
              item.swiftPrefix.startsWith(value.slice(0, value.length === 4 ? 4 : 6)),
          );
}

/** Resolve a display-only suggestion. Conflicting clues and ambiguous abbreviations yield no guess. */
export function accountInstitution(
    details: Record<string, string>,
    accountName?: string,
    kind?: string,
): Institution | undefined {
    if (kind === "cash") return undefined;

    const payment = kind ? paymentInstitutions.get(kind) : undefined;
    if (payment) return getInstitution(payment);

    const candidates =
        kind === "crypto"
            ? CRYPTO_PLATFORMS
            : kind && ["bank", "credit_card", "debit_card"].includes(kind)
              ? BANK_INSTITUTIONS
              : INSTITUTIONS;
    if (details.institution) return candidates.find(({ id }) => id === details.institution);

    const matches = [details.bank_name, details.issuer_name, accountName]
        .filter((name): name is string => !!name)
        .map((name) => matchingNames(name, candidates));
    if (details.swift_bic) matches.push(matchingSwift(details.swift_bic, candidates));
    const clues = matches.filter((group) => group.length > 0);
    if (!clues.length) return undefined;
    const possible = clues[0].filter((entry) => clues.every((group) => group.includes(entry)));
    return possible.length === 1 ? possible[0] : undefined;
}
